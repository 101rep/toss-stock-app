def make_obj(x):
    code, y_sym, name, market, price, change, diff, vol, amount, v30, v60, v90, chg_since_surge, inst, forgn, high_dist, rsi = x
    return {
        "code": code,
        "yahooSymbol": y_sym,
        "name": name,
        "market": market,
        "price": price,
        "change": change,
        "diff": diff,
        "vol": vol,
        "relVol": f"{v30}배",
        "vol30": v30,
        "vol60": v60,
        "vol90": v90,
        "chgSinceSurge": chg_since_surge, # 거래량 터진 후 가격 등락률(%)
        "amount": amount,
        "instNet": inst,                  # 기관 순매수
        "foreignNet": forgn,              # 외국인 순매수
        "highDistance": high_dist,        # 52주 신고가 대비 거리 (%)
        "rsi": rsi,                       # RSI 보조지표 (0~100)
        "isEtf": False
    }

